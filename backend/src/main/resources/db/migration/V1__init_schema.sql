-- ---------------------------------------------------------------------
-- contact settings (singleton row) + social links
-- ---------------------------------------------------------------------
CREATE TABLE contact_settings (
    id                 SMALLINT     PRIMARY KEY DEFAULT 1,
    whatsapp_number    VARCHAR(20),                             -- digits only, intl format, e.g. 201201200208
    instagram_username VARCHAR(30),                             -- without '@'
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_contact_settings_singleton CHECK (id = 1),
    CONSTRAINT ck_contact_settings_whatsapp CHECK (whatsapp_number IS NULL OR whatsapp_number ~ '^[1-9][0-9]{7,14}$'),
    CONSTRAINT ck_contact_settings_instagram CHECK (instagram_username IS NULL OR instagram_username ~ '^[A-Za-z0-9._]{1,30}$')
);
INSERT INTO contact_settings (id) VALUES (1);

CREATE TABLE social_link (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform      VARCHAR(20)  NOT NULL,
    url           VARCHAR(500) NOT NULL,                        -- https only (validated in DTO)
    display_order INT          NOT NULL DEFAULT 0,
    CONSTRAINT ck_social_link_platform CHECK (platform IN ('FACEBOOK', 'TIKTOK', 'YOUTUBE', 'X', 'PINTEREST', 'BEHANCE', 'EMAIL', 'WEBSITE', 'OTHER'))
);
CREATE INDEX ix_social_link_display_order ON social_link (display_order);

-- ---------------------------------------------------------------------
-- stats: anonymous, daily-aggregated contact-button clicks
-- (polymorphic item reference: rows are deleted by the service when the item is deleted)
-- ---------------------------------------------------------------------
CREATE TABLE contact_click_daily (
    item_type   VARCHAR(10) NOT NULL,
    item_id     BIGINT      NOT NULL,
    channel     VARCHAR(10) NOT NULL,
    day         DATE        NOT NULL,
    click_count BIGINT      NOT NULL DEFAULT 0,
    PRIMARY KEY (item_type, item_id, channel, day),
    CONSTRAINT ck_click_item_type CHECK (item_type IN ('PRODUCT', 'EVENT')),
    CONSTRAINT ck_click_channel   CHECK (channel IN ('WHATSAPP', 'INSTAGRAM')),
    CONSTRAINT ck_click_count     CHECK (click_count >= 0)
);
CREATE INDEX ix_contact_click_daily_day ON contact_click_daily (day);

-- ---------------------------------------------------------------------
-- audit log (append-only)
-- ---------------------------------------------------------------------
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actor       VARCHAR(254) NOT NULL,                          -- admin email, or attempted email for failed logins
    action      VARCHAR(30)  NOT NULL,
    entity_type VARCHAR(30),
    entity_id   VARCHAR(64),
    ip_address  VARCHAR(45),
    details     JSONB,
    CONSTRAINT ck_audit_log_action CHECK (action IN (
        'LOGIN_SUCCESS', 'LOGIN_FAILURE', 'ACCOUNT_LOCKED', 'LOGOUT', 'TOKEN_REUSE_DETECTED',
        'PASSWORD_CHANGED', 'CREATE', 'UPDATE', 'DELETE'))
);
CREATE INDEX ix_audit_log_occurred_at ON audit_log (occurred_at DESC);
CREATE INDEX ix_audit_log_action      ON audit_log (action, occurred_at DESC);
